export const CAN_DOS: CanDo[] = (Object.keys(D) as CefrSkill[]).flatMap((skill) =>
  (Object.keys(D[skill]) as Cefr[]).flatMap((level) =>
    D[skill][level].map(([text, example], i) => ({ id: `${skill}-${level}-${i}`, skill, level, text, example }))
  )
);

export function canDosFor(level: Cefr, skill?: CefrSkill): CanDo[] {
  return CAN_DOS.filter((c) => c.level === level && (!skill || c.skill === skill));
}

